import { posix } from 'node:path';

import { defineConfig } from 'orval';

import { ROOTS, SHARED, listYaml } from './scripts/lib/roots.mjs';

type Entries = Parameters<typeof defineConfig>[0];

// One set of entries per OpenAPI document, discovered here so that adding a spec needs no change in
// this file:
// - every document gives its TypeScript types and its zod validators to @cadenway/contracts. The
//   types name each schema of the document (`Task`, `Problem`); the validators are written per
//   operation, with the schemas inlined and without the error responses, so they do not replace
//   the types;
// - a document of openapi/public also gives its Angular services to @cadenway/api-client, the one
//   surface the applications call.
// The events of asyncapi/ are generated by scripts/generate-events.mjs, not by orval.
const entries: Record<string, unknown> = {};

// orval refuses a `$ref` to another file unless that file is listed, relative to the spec.
const shared = listYaml(SHARED).map((file) => `${SHARED}/${file}.yaml`);

for (const root of ROOTS) {
  for (const spec of listYaml(root.openapi)) {
    const id = `${root.name}-${spec.replaceAll('/', '-')}`;
    const target = `${root.openapi}/${spec}.yaml`;
    const input = {
      target,
      parserOptions: {
        externalRefs: {
          allow: shared.map((file) => posix.relative(posix.dirname(target), file)),
        },
      },
    };
    // Says where the module comes from, without the name of the generator release.
    const override = {
      header: (): string[] => [
        `Generated by orval from ${target}.`,
        'Do not edit: change the spec and run `pnpm generate`.',
      ],
    };

    entries[`${id}-types`] = {
      input,
      output: {
        schemas: {
          path: `${root.contracts}/types/${spec}.ts`,
          mode: 'single',
          type: 'typescript',
        },
        override,
      },
    };

    entries[`${id}-validators`] = {
      input,
      output: {
        client: 'zod',
        mode: 'single',
        target: `${root.contracts}/validators/${spec}.ts`,
        override,
      },
    };

    if (spec.startsWith('public/')) {
      entries[`${id}-client`] = {
        input,
        output: {
          client: 'angular',
          mode: 'tags-split',
          target: `${root.client}/${spec}`,
          schemas: `${root.client}/${spec}/model`,
          override,
        },
      };
    }
  }
}

export default defineConfig(entries as Entries);
