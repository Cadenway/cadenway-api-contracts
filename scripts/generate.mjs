#!/usr/bin/env node
/**
 * Regenerates the generated trees of both packages from the specs (`pnpm generate`).
 *
 * Usage: `node scripts/generate.mjs [--openapi <dir>] [--asyncapi <dir>] [--out <dir>]`. The
 * defaults are `openapi/`, `asyncapi/` and `packages/`; the pipeline tests point the three at the
 * fixtures and at a temporary directory.
 *
 * Written below `<out>`, every previous content of the two `generated/` folders being removed:
 *
 * - `contracts/src/generated/types/<spec>.ts`: TypeScript types of an OpenAPI document (orval);
 * - `contracts/src/generated/validators/<spec>.ts`: zod validators of its operations (orval);
 * - `contracts/src/generated/events/<spec>.ts`: event names and payload types of an AsyncAPI
 *   document (Modelina, see `generate-events.mjs`);
 * - `api-client/src/generated/<spec>/`: Angular services and their types, for the documents of
 *   `public/` only, the one surface the applications call (orval);
 * - `api-client/src/public-api.ts`: the entry point of the Angular library, one explicit export per
 *   generated declaration.
 *
 * `<spec>` is the path of the document below its folder, without extension (`public/tasks`). Each
 * contracts module stands alone and is reached through a subpath of `@waypoint/contracts`, so two
 * documents may use the same schema name. The Angular library has a single entry point: a name
 * declared by two public documents is exported once when both declarations are identical, and
 * stops the generation otherwise.
 *
 * Without any spec the script removes the generated folders and writes an empty public API.
 */
import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import path from 'node:path';

import { generate as orval } from 'orval';
import * as prettier from 'prettier';
import ts from 'typescript';

import { generateEvents } from './generate-events.mjs';
import { listFiles, listSpecFiles, parseArguments, repoRoot } from './lib/specs.mjs';

const HEADER_LINE = 'Generated by `pnpm generate`. Do not edit.';
const HEADER = `/**\n * ${HEADER_LINE}\n */`;
const PUBLIC_SURFACE = 'public/';

/** Options shared by every orval run: quiet unless something is wrong, and failing loudly. */
const ORVAL_RUN = { logLevel: 'warn', throwOnError: true };

/** Path of a spec below its folder, without extension, with forward slashes. */
const specName = (relative) => relative.replace(/\.(ya?ml|json)$/i, '');

/** Runs orval for one document. The header replaces orval's own, which embeds the spec title. */
async function runOrval(target, output) {
  await orval(
    {
      input: { target },
      output: {
        indexFiles: false,
        ...output,
        override: { header: () => [HEADER_LINE], ...output.override },
      },
    },
    repoRoot,
    ORVAL_RUN,
  );
}

/** Generates the types and the validators of one OpenAPI document into the contracts package. */
async function generateContracts(source, name, generated) {
  await runOrval(source, {
    client: 'zod',
    mode: 'single',
    target: path.join(generated, 'validators', `${name}.ts`),
    schemas: { path: path.join(generated, 'types', `${name}.ts`), mode: 'single' },
    // Pinned: the default infers the major from the installed package.
    override: { zod: { version: 4 } },
  });
}

/** Generates the Angular services of one public OpenAPI document into the api-client package. */
async function generateClient(source, name, generated) {
  const folder = path.join(generated, name);
  await runOrval(source, {
    client: 'angular',
    // One service per tag, named after it.
    mode: 'tags',
    target: path.join(folder, `${path.posix.basename(name)}.ts`),
    schemas: path.join(folder, 'model'),
  });
}

/**
 * Lists the declarations a generated module exports, by reading its syntax only.
 *
 * @returns {Map<string, 'type' | 'value'>} `value` when the name exists at run time, including a
 *   constant that shares its name with a type.
 */
function readExports(file) {
  const source = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest);
  const found = new Map();
  const add = (name, kind) => {
    if (kind === 'value' || !found.has(name)) found.set(name, kind);
  };
  for (const statement of source.statements) {
    if (ts.isExportDeclaration(statement) || ts.isExportAssignment(statement)) {
      throw new Error(
        `${file}: re-exports and default exports are not expected in generated code.`,
      );
    }
    const exported =
      ts.canHaveModifiers(statement) &&
      ts.getModifiers(statement)?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword);
    if (!exported) continue;
    if (ts.isInterfaceDeclaration(statement) || ts.isTypeAliasDeclaration(statement)) {
      add(statement.name.text, 'type');
    } else if (
      (ts.isClassDeclaration(statement) ||
        ts.isFunctionDeclaration(statement) ||
        ts.isEnumDeclaration(statement)) &&
      statement.name
    ) {
      add(statement.name.text, 'value');
    } else if (ts.isVariableStatement(statement)) {
      for (const declaration of statement.declarationList.declarations) {
        if (!ts.isIdentifier(declaration.name)) {
          throw new Error(`${file}: destructured exports are not expected in generated code.`);
        }
        add(declaration.name.text, 'value');
      }
    } else {
      throw new Error(`${file}: unexpected exported statement in generated code.`);
    }
  }
  return found;
}

/**
 * Builds the entry point of the Angular library from the generated modules.
 *
 * @param {string} sourceDirectory The `src/` folder of the library.
 * @param {string[]} modules Generated modules, relative to it, sorted.
 * @returns {string} Unformatted TypeScript source.
 */
function renderPublicApi(sourceDirectory, modules) {
  const owners = new Map();
  const statements = [];
  for (const module of modules) {
    const file = path.join(sourceDirectory, module);
    const kept = { value: [], type: [] };
    for (const [name, kind] of readExports(file)) {
      const owner = owners.get(name);
      if (owner === undefined) {
        owners.set(name, file);
        kept[kind].push(name);
      } else if (readFileSync(owner, 'utf8') !== readFileSync(file, 'utf8')) {
        const first = path.relative(sourceDirectory, owner).replaceAll('\\', '/');
        throw new Error(
          `"${name}" is declared differently in ${first} and ${module}: one entry point cannot export both. Share one schema between the specs, or rename one.`,
        );
      }
    }
    const from = `'./${module.replace(/\.ts$/, '')}'`;
    if (kept.value.length > 0)
      statements.push(`export { ${kept.value.sort().join(', ')} } from ${from};`);
    if (kept.type.length > 0)
      statements.push(`export type { ${kept.type.sort().join(', ')} } from ${from};`);
  }

  const docblock = [
    '/**',
    ' * Public API of `@waypoint/api-client`: the Angular services generated from the public OpenAPI',
    ' * documents, with the types of their parameters and results.',
    ' *',
    ' * Written by `pnpm generate` (`scripts/generate.mjs`), one explicit export per declaration. Do not',
    ' * edit it: change the specs or the generator, then regenerate.',
    ' */',
  ].join('\n');
  return `${docblock}\n${statements.length > 0 ? statements.join('\n') : 'export {};'}\n`;
}

async function main() {
  const { options } = parseArguments(process.argv.slice(2), {
    openapi: 'openapi',
    asyncapi: 'asyncapi',
    out: 'packages',
  });
  const openapiDirectory = path.resolve(repoRoot, options.openapi);
  const asyncapiDirectory = path.resolve(repoRoot, options.asyncapi);
  const outDirectory = path.resolve(repoRoot, options.out);

  const contractsGenerated = path.join(outDirectory, 'contracts', 'src', 'generated');
  const clientSource = path.join(outDirectory, 'api-client', 'src');
  const clientGenerated = path.join(clientSource, 'generated');
  rmSync(contractsGenerated, { recursive: true, force: true });
  rmSync(clientGenerated, { recursive: true, force: true });

  const specs = listSpecFiles(openapiDirectory, 'openapi');
  const names = specs.map(specName);
  const repeated = names.find((name, index) => names.indexOf(name) !== index);
  if (repeated) throw new Error(`Two OpenAPI documents are named ${repeated}; keep one extension.`);

  for (const relative of specs) {
    const source = path.join(openapiDirectory, relative);
    const name = specName(relative);
    await generateContracts(source, name, contractsGenerated);
    if (name.startsWith(PUBLIC_SURFACE)) {
      await generateClient(source, name.slice(PUBLIC_SURFACE.length), clientGenerated);
    }
  }

  const events = await generateEvents({ specsDirectory: asyncapiDirectory, header: HEADER });
  for (const { file, content } of events) {
    const target = path.join(contractsGenerated, 'events', file);
    mkdirSync(path.dirname(target), { recursive: true });
    writeFileSync(target, content);
  }

  const clientModules = listFiles(clientGenerated).map((file) => `generated/${file}`);
  const publicApi = path.join(clientSource, 'public-api.ts');
  mkdirSync(clientSource, { recursive: true });
  writeFileSync(publicApi, renderPublicApi(clientSource, clientModules));

  // One formatting pass over everything written, with the repository configuration: the output is
  // the same whatever the generators emit, and `generated/` is ignored by `pnpm format`.
  const style = await prettier.resolveConfig(path.join(repoRoot, 'package.json'));
  const written = [
    ...listFiles(contractsGenerated).map((file) => path.join(contractsGenerated, file)),
    ...clientModules.map((file) => path.join(clientSource, file)),
    publicApi,
  ];
  for (const file of written) {
    const formatted = await prettier.format(readFileSync(file, 'utf8'), {
      ...style,
      filepath: file,
    });
    writeFileSync(file, formatted);
  }

  console.log(
    `generate: ${specs.length} OpenAPI document(s), ${events.length} AsyncAPI document(s), ${written.length} file(s) written below ${options.out}.`,
  );
}

try {
  await main();
} catch (error) {
  // The message says which document or name is at fault; the stack of a generator adds nothing.
  console.error(`generate: ${error instanceof Error ? error.message : String(error)}`);
  process.exit(1);
}
